def map_tag(t, canon):
    if t in EXACT: return EXACT[t]
    for pat, c in RULES:
        if re.search(pat, t, re.I): return c
    return t  # 保留为新标签

if __name__ == "__main__":
    doc = DOC.read_text(encoding="utf-8")
    tags = []
    for b in re.split(r"(?m)^### ", doc)[1:]:
        m = re.search(r"\*\*标签\*\*：(.+?)(?:\u3000|$)", b, re.M)
        if m: tags += [t.strip() for t in re.split(r"[、,，]", m.group(1)) if t.strip()]
    cnt = collections.Counter(tags)
    mapping = {t: map_tag(t, CANON) for t in cnt}
    used = collections.Counter(mapping.values())
    keep = sorted(set(mapping.values()) - set(CANON))
    out = {"canon": CANON, "map": mapping, "new": keep}
    (ROOT / "tools" / "tag-map.json").write_text(json.dumps(out, ensure_ascii=False, indent=1), encoding="utf-8")
    print("orig", len(cnt), "-> canon", len(set(mapping.values())), "new-kept", len(keep))
    print("top:", used.most_common(15))
    print("new:", keep[:20])
